#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""新規スポットの掲載予定データをCodexに独立検証させるプロンプトを作る。

既存スポットの再検証（build_codex_spot_prompt.py）と同じ考え方。
違いは、新規なので git HEAD に「修正前」が無いこと。掲載予定データそのものを渡し、
「実態と違う項目はどれか」「足りないものは何か」「そもそも犬連れで行ける施設か」を
自分で調べて答えてもらう。Claude側の出典・根拠・迷った点は渡さない（引きずられるため）。

使い方:
    python scripts/build_codex_newspot_prompt.py --files a.json,b.json --out prompt.txt
    cat prompt.txt | codex exec --skip-git-repo-check -
"""
import argparse, io, json, sys

sys.stdout.reconfigure(encoding="utf-8")

HEAD = """あなたは独立した検証役です。下に「関西の犬連れお出かけスポット検索サイト」に新しく載せる予定の
スポットデータがあります。これは別のAIが調べて書いたもので、**まだ誰も検証していません**。
あなたの仕事は、データを鵜呑みにせず**自分でウェブを調べて**、実態と違う項目・足りない項目を見つけることです。

## 進め方（必ず守る）
- **書かれている内容に引きずられないこと。** まず自分で公式サイト・自治体サイト・地図サイト・個人ブログ・SNSを開いて事実を集め、そのあとでデータと比べる
- **実際にページを開いて確認したURLだけ**を根拠にする。検索結果のスニペットだけで判断しない
- 分からないものは「確認できず」と書く。推測で「不一致」にしない
- **不一致＝違う内容を実際に確認できた時だけ。**「探したが見つからなかった」は確認できず
- 設備が無いことは書かれていないことで示される。`false` は「無い・不可の証拠」を見つけた時だけ指摘する。`null` は未確認の意味なので、値を確認できたら教えてほしい
- 数値の出典が割れる時は、日付が新しい方を優先し、両方のURLを書く

## 各スポットについて答えること
1. **犬連れで行ける施設か**（最重要）。公式の記載を原文で引用（「ペット同伴可」「ペット不可」「リード着用」など）。公式に記載が無ければ、犬連れで訪問した報告（ブログ・Instagram・X・口コミ）のURLを2件以上。**公式が「ペット不可」と明記していれば掲載不可と答える**
2. 項目ごとの判定: 住所（番地）／緯度経度（施設の中心か）／駐車場の有無・無料有料・料金・台数／トイレ／ドッグラン／入場料／営業時間・定休日／犬のサイズ制限・マナー条件／見頃の時期／公式URL／別名 … それぞれ **一致／不一致／確認できず** と根拠URL。不一致なら正しい値
3. **足りないもの探し**: データに書かれていない犬連れ向けの条件や設備（リード長の制限、立入禁止エリア、マナーベルト、水飲み場、足洗い場、季節の駐車規制、有料化予定、閉鎖情報、2025〜2026年の料金改定）
4. remarks（解説文）に**事実として誤っている記述**があれば指摘（文体は見なくてよい）
5. 総合判定: **掲載してよい／修正すれば掲載可／掲載すべきでない** と理由

## 出力の形式
スポットごとに見出しを立て、上の1〜5を書く。最後に全スポットの一覧表（掲載可否・不一致の件数・確認できずの件数）。
調査は全体で20分を目安に切り上げ、間に合わなかったスポットは「未調査」と書く。

## 掲載予定データ
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--files", required=True, help="カンマ区切りのJSONファイル")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    parts = [HEAD]
    for i, f in enumerate(a.files.split(","), 1):
        d = json.load(io.open(f.strip(), encoding="utf-8"))
        if d.get("verdict"):
            continue
        # 検証役に渡すのはデータだけ。出典や迷った点は渡さない
        parts.append(f"\n### スポット{i}: {d.get('name')}\n```json\n{json.dumps(d, ensure_ascii=False, indent=1)}\n```\n")
    io.open(a.out, "w", encoding="utf-8").write("".join(parts))
    print(f"wrote {a.out} ({len(parts)-1} spots)")


if __name__ == "__main__":
    main()
