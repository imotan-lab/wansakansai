# -*- coding: utf-8 -*-
"""スポット5件をCodexに独立検証させるためのプロンプトファイルを作る。

★2026-09-07に「修正した分だけ検証」から「対象5件すべてを検証」に変えた★
それまでは、Claudeが直すと決めた項目だけをCodexに見せていた。つまり
**「直さなくていい」という判断は誰も検証していなかった**。
間違って直せばCodexが気づくが、間違って見逃しても誰も気づかない。
見逃されたスポットはチェック回数が+1されて順番が後ろに回るので、
そのまま長期間放置される。

★Codexに「Claudeがどう判断したか」を見せないこと★
見せると引きずられて、いちばん拾いたい「Claudeが見落とした項目」が出てこない。
このスクリプトは **修正前（git HEAD）のデータ**だけを渡して、
「実態と違うのはどれか」を独立に答えてもらう。突き合わせはClaude側が後で行う。

修正前のデータを使うのは、STEP 4でspots.jsonをすでに編集しているため。
編集後を渡すと「Claudeの結論」を渡すことになってしまう。

★2026-09-07の実測。次の2つの文言を消さないこと★
  ①「設備が無いことは書かれていないことで示される。false は『ある証拠』を見つけた時だけ指摘する」
  ②「項目7＝掲載データに書かれていない犬連れ向け設備が新設されていないか（足りないもの探し）」
同じ5件（michinoeki-kannabe-kogen ほか）で3回試した結果:
  1回目（①なし）… dogRun.available を5件中4件で「false→null」と誤指摘。
                    toilet.western も5件全部「確認できず」。公式が便器の種類を書くことはまず無く、
                    毎回必ずこうなるため本当に見てほしい料金・営業時間の指摘が埋もれた。
                    ただし副作用でドッグラン周りを深掘りし、屋上の犬同伴エリアを発見した
  2回目（①を追加）… 誤指摘はゼロになったが、**副産物だった本物の発見も消えた**
  3回目（①＋②）… 誤指摘ゼロのまま、犬同伴エリアの発見が戻った
**副作用に頼らず、欲しいものは直接聞くこと。** 誤検知を潰すと副産物も一緒に消える。

使い方:
    python scripts/build_codex_spot_prompt.py --ids id1,id2,... --out 出力先.txt
    cat 出力先.txt | codex exec --skip-git-repo-check -
    （★プロンプトはファイルに書いてパイプで渡すこと。コマンド直書きはshell_guardに止められる★）
"""
import argparse
import io
import json
import subprocess
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent

# 検証してほしい項目。spots.json の全フィールドを投げると量が多すぎるので、
# 「変わりやすく、間違っていると利用者が困る」ものに絞る。
FIELDS = [
    "name", "address", "lat", "lng", "officialUrl",
    "parking", "toilet", "dogRun", "admission", "dogSize",
    "tags", "remarks",
]

HEADER = """あなたは犬連れお出かけ情報サイト「わんさかんさい」の掲載内容を検証する役です。

# やってほしいこと

下に、サイトに現在掲載している{n}件のスポットのデータを載せます。
**それぞれについて、掲載内容が「今の実態」と合っているかを調べてください。**

- 合っていない項目があれば、正しい値を教えてください。
- 全部合っているなら「問題なし」と書いてください。

# 最初に読むこと

- **別のAI（Claude）も同じ{n}件を調べていますが、その結論はあなたには見せません。**
  引きずられずに、自分で調べた結果だけを書いてください。
  （あとで2つの結論を突き合わせます。違っていて構いません。むしろ違いを見つけるのが目的です）
- **実際にページを開いて確認できたことだけを根拠にしてください。** 検索結果の要約を根拠にしないこと。
  推測で埋めないこと。
- **★「不一致」と「確認できず」を混ぜないでください。ここが一番大事です★**
  - **不一致** … **違う内容を実際に確認できた時だけ**使います。
    例: 公式に「500円」と書いてあるのに、掲載データが「400円」になっている。
  - **確認できず** … 探したが根拠のページに行き当たらなかった時に使います。
  **「探したが見つからなかった」は不一致ではありません。** 必ず「確認できず」と書いてください。
  こちらは不一致を「2つのAIで結論が割れた」として扱い、公式を開き直して調べ直します。
  見つからなかっただけのものを不一致にされると、その時間が丸ごと無駄になります。
- **媒体名だけでドメインを決めつけないでください。** 同じ発行元が複数のサイトに出します。
  施設も、公式サイトとInstagramで書いてある内容が違うことがあります。
  小規模なドッグラン・ドッグカフェは公式サイトを持たず、Instagramだけで
  料金改定や定休日を告知していることがあります。
- 根拠にしたURLを必ず書いてください。

# このサイトの決まり

- 情報の優先順位は ①現在の公式案内 ②施設への直接確認 ③個人ブログ・SNSの訪問報告 の順。
- **★「設備が無い」は、書かれていないことで示されます★**
  公園や施設が「うちにドッグランはありません」「洋式トイレはありません」と書くことはありません。
  そのため、**`false` になっている項目を「無いと明記されていない」という理由で指摘しないでください。**
  指摘してよいのは、**実際に「ある」証拠を見つけた時だけ**です
  （例: 公式に犬同伴エリアの案内が載っていたのに `dogRun.available` が false になっている）。
- **★公式がふつう書かない項目は、反対の証拠が無いかぎり報告しないでください★**
  `toilet.western`（便器が洋式か）は、公式サイトにまず載りません。毎回「確認できず」と書かれると、
  本当に見てほしい料金や営業時間の指摘が埋もれます。**違う内容を実際に見つけた時だけ**書いてください。
- 逆に、**掲載データが `true` や具体的な数値を主張しているのに、公式でまったく裏が取れない**場合は
  指摘してください（例: 「ウォシュレット完備」と書いてあるが公式に一切記載がない）。
  ただしこれも「毎回どの施設でも言える」たぐいのものは省いてください。
- 営業時間・料金・禁止事項など**管理者が決める情報は公式を優先**します。
- **恒常的な事柄だけを書きます。** 臨時休業・期間限定価格・今シーズンだけのイベントは載せません。
  それらが載っていたら「不一致（削除すべき）」としてください。
- `remarks` は常体・体言止め中心の1段落です。文体そのものは検証対象外です。

# とくに見てほしいところ

変わりやすく、間違っていると利用者が現地で困るものです。
**下の7つを優先してください。** それ以外の細かい相違は、見つけても書かなくて構いません
（細かい指摘が並ぶと、本当に困るものが埋もれます）。

1. **料金**（入場料・ドッグラン利用料・駐車料金）。値上げ・有料化されていませんか。
   「無料」と書いてあるものが有料になっていませんか（特定のエリアだけ有料化される例が多い）
2. **営業時間・定休日**。季節で変わる場合はその区別も
3. **犬連れの可否と条件**（リード・エリア分離・サイズ制限・ワクチン証明・マナーパンツ）。
   犬NGに変わっていませんか。逆に、根拠なく「不可」と書いていませんか
4. **駐車場**（有無・無料/有料・台数）
5. **施設そのものの存続**。閉鎖・移転・改称していませんか
6. **公式URL**が生きているか
7. **★掲載データに書かれていない、犬連れ向けの設備・サービスが新しくできていないか★**
   ここだけは「間違い探し」ではなく「**足りないもの探し**」です。
   犬同伴エリア・ドッグラン・犬用の水飲み場やシャワー・同伴可のテラス席などが
   新設・拡張されていないか調べて、あれば教えてください。
   **公式に「ある」と確認できた場合だけ**書いてください（無いことの証明は求めていません）。
   例: 掲載データは「屋外の散策が中心」としか書いていないが、公式に犬同伴エリアの案内が新設されていた。
   犬連れの人にとっては、間違いが直ることと同じくらい、行ける場所が増えたと分かることが重要です。

# 書き方

スポットごとに、必ずこの形で書いてください。行頭の記号も含めて守ってください。

```
## {{スポットID}}
- 総合: 問題なし | 要修正 | 確認できず
- 項目ごと（要修正のものだけ書く。無ければ「なし」）:
  - {{項目名}}: 不一致 | 確認できず ／ 掲載値 → 正しいと思う値 ／ 理由
- 根拠URL: （実際に開いたものだけ）
```

「問題なし」＝掲載内容のままでよい、「要修正」＝直すべき項目がある、
「確認できず」＝調べたが判断できなかった、です。

"""


def load_spots_at_head():
    """git HEAD 時点の spots.json を読む（今日の編集を含まない状態）。"""
    r = subprocess.run(["git", "-C", str(BASE), "show", "HEAD:data/spots.json"],
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    if r.returncode != 0 or not r.stdout.strip():
        return None
    try:
        return {s["id"]: s for s in json.loads(r.stdout)}
    except Exception:
        return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ids", required=True, help="対象スポットIDをカンマ区切りで")
    ap.add_argument("--out", required=True, help="プロンプトの出力先")
    ap.add_argument("--from-working", action="store_true",
                    help="git HEAD ではなく作業ツリーの spots.json を使う（通常は使わない）")
    a = ap.parse_args()

    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

    want = [s.strip() for s in a.ids.split(",") if s.strip()]
    if not want:
        print("!! --ids が空")
        return 1

    if a.from_working:
        by_id = {s["id"]: s
                 for s in json.load(io.open(BASE / "data" / "spots.json", encoding="utf-8"))}
        src = "作業ツリー"
    else:
        by_id = load_spots_at_head()
        if by_id is None:
            print("!! git HEAD から spots.json を読めなかった。--from-working で作業ツリーを使うこと")
            return 1
        src = "git HEAD（今日の修正を含まない状態）"

    missing = [i for i in want if i not in by_id]
    if missing:
        print(f"!! spots.jsonに無いID: {','.join(missing)}")
        return 1

    body = HEADER.format(n=len(want))
    body += "\n# 検証してほしいスポット\n\n"
    for i in want:
        s = by_id[i]
        trimmed = {k: s.get(k) for k in FIELDS if k in s}
        trimmed["id"] = i
        body += f"## {i}\n\n```json\n"
        body += json.dumps(trimmed, ensure_ascii=False, indent=2)
        body += "\n```\n\n"

    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    io.open(a.out, "w", encoding="utf-8", newline="\n").write(body)
    print(f"[key] Codexプロンプト作成 件数={len(want)} 出典={src}")
    print(f"出力: {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
